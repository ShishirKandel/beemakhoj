// Merge research/companies/*.json + research/market-context.json into site/js/data.js.
// Validates against research/SCHEMA.md rules and prints problems; invalid policies are dropped.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1')), '..');
const dir = path.join(root, 'research', 'companies');
const CATS = new Set(['term-life', 'endowment', 'money-back', 'child-plan', 'pension', 'whole-life', 'foreign-employment',
  'health', 'critical-illness', 'personal-accident', 'motor-bike', 'motor-car', 'travel', 'home', 'livestock', 'crop']);
const TYPES = new Set(['life', 'nonlife', 'micro-life', 'micro-nonlife', 'reinsurance']);
const isNum = (x) => typeof x === 'number' && isFinite(x);

function pricingOk(p) {
  switch (p && p.model) {
    case 'rate-per-thousand': return isNum(p.ratePer1000AtAge30) && p.ratePer1000AtAge30 > 0 && isNum(p.referenceTerm);
    case 'health-bands': return Array.isArray(p.bands) && p.bands.length > 0 && p.bands.every((b) => isNum(b.sumInsured) && isNum(b.annualPremiumAge30));
    case 'percent-of-value': return isNum(p.ratePercent) && p.ratePercent > 0;
    case 'fixed': return isNum(p.annualPremium);
    case 'per-day': return isNum(p.perDayPremium) && isNum(p.coverAmount);
    default: return false;
  }
}

const companies = [], policies = [], problems = [];
const seenPolicy = new Set();
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  let j;
  try { j = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8').replace(/^﻿/, '')); }
  catch (e) { problems.push(`${f}: invalid JSON (${e.message})`); continue; }
  const c = j.company;
  if (!c || !c.id || !c.name || !TYPES.has(c.type)) { problems.push(`${f}: bad company block`); continue; }
  if (companies.some((x) => x.id === c.id)) { problems.push(`${f}: duplicate company ${c.id}`); continue; }
  c.shortName = c.shortName || c.name.replace(/\s*(Insurance|Company|Limited|Ltd\.?|Co\.?)\b.*$/i, '').trim();
  companies.push(c);
  for (const p of j.policies || []) {
    const why = [];
    if (!p.id || seenPolicy.has(p.id)) why.push('missing/duplicate id');
    if (p.companyId !== c.id) { p.companyId = c.id; }
    if (!CATS.has(p.category)) why.push(`bad category "${p.category}"`);
    if (!pricingOk(p.pricing)) why.push('bad pricing');
    if (!p.name) why.push('no name');
    if (why.length) { problems.push(`${f}: policy ${p.id || '?'} dropped — ${why.join(', ')}`); continue; }
    // Pure term cover is non-participating; a bonus here means the record is mislabelled or mixed up.
    if (p.category === 'term-life' && p.bonusRatePer1000) problems.push(`${f}: policy ${p.id} is term-life but has a bonus rate — check the category`);
    seenPolicy.add(p.id);
    p.features = p.features || []; p.benefits = p.benefits || []; p.exclusions = p.exclusions || []; p.riders = p.riders || []; p.bestFor = p.bestFor || [];
    p.eligibility = p.eligibility || {};
    p.dataConfidence = p.dataConfidence || 'estimated';
    policies.push(p);
  }
}

let context = {};
const ctxFile = path.join(root, 'research', 'market-context.json');
if (fs.existsSync(ctxFile)) {
  try { context = JSON.parse(fs.readFileSync(ctxFile, 'utf8').replace(/^﻿/, '')); }
  catch (e) { problems.push(`market-context.json: invalid JSON (${e.message})`); }
}

const out = `/* Generated by tools/build-data.mjs — do not edit by hand. */\nwindow.NIDATA = ${JSON.stringify({ builtAt: new Date().toISOString().slice(0, 10), companies, policies, context }, null, 1)};\n`;
fs.writeFileSync(path.join(root, 'site', 'js', 'data.js'), out, 'utf8');

const byCat = {};
for (const p of policies) byCat[p.category] = (byCat[p.category] || 0) + 1;
console.log(`companies: ${companies.length}  policies: ${policies.length}`);
console.log('by type:', companies.reduce((a, c) => ((a[c.type] = (a[c.type] || 0) + 1), a), {}));
console.log('by category:', byCat);
if (problems.length) { console.log(`\n${problems.length} problem(s):`); problems.forEach((p) => console.log(' - ' + p)); }
